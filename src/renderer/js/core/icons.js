/**
 * Resolve an icon name (or alias) to its inner markup.
 * @param {string} name
 * @returns {string|null}
 */
export function iconMarkup(name) {
  if (typeof name !== 'string') return null;
  const key = Object.prototype.hasOwnProperty.call(ICONS, name) ? name : ICON_ALIASES[name];
  return key && Object.prototype.hasOwnProperty.call(ICONS, key) ? ICONS[key] : null;
}

/**
 * Names of every icon (without aliases), sorted.
 * @returns {string[]}
 */
export function iconNames() {
  return Object.keys(ICONS).sort();
}

